export type TKey = keyof typeof en;
export type T = (key: TKey, vars?: Record<string, string | number>) => string;

const DICTS: Record<Lang, Dict> = { en, zh };

export function makeT(lang: Lang): T {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

const I18nContext = createContext<{ lang: Lang; t: T }>({ lang: "en", t: makeT("en") });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <I18nContext.Provider value={{ lang, t: makeT(lang) }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
export const useT = () => useContext(I18nContext).t;
